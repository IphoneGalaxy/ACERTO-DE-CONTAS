const fs = require('node:fs');
const assert = require('node:assert/strict');
const html = fs.readFileSync(__dirname + '/index.html', 'utf8');
const source = html.slice(html.indexOf('      const parseNubankAmount ='), html.indexOf('      // --- PARSER ITAÚ PDF ---'));
const norm = s => String(s || '').normalize('NFD').replace(/[\u0300-\u036f]/g, '').trim().toLowerCase();
const parse = new Function('norm', source + '; return parseNubankCsv;')(norm);
const header = ['date','title','amount'];
const row = (title, value) => ['2026-09-25', title, value];
const pending = row('Valor pendente do mês anterior','344,78');
const purchase = row('Loja - Parcela 4/5','71,00');
const run = rows => parse([header,...rows],{},'family','2026-10').expenses;
const sum = rows => Math.round(rows.reduce((n,e)=>n+e.amount,0)*100);
assert.equal(sum(run([pending,row('Pagamento recebido','- 344,78'),purchase])),7100);
assert.equal(sum(run([row('Pagamento recebido','- 344,78'),pending,purchase])),7100);
assert.equal(sum(run([pending,row('Pagamento recebido','- 100,00'),purchase])),31578);
assert.equal(sum(run([pending,purchase])),41578);
assert.equal(sum(run([pending,row('Pagamento recebido','- 500,00'),purchase])),7100);
assert.equal(sum(run([pending,row('Estorno','- 344,78'),purchase])),7100);
assert.equal(run([row('Valor pendente do mês anterior','100,00'),row('Valor pendente do mês anterior','100,00'),row('Pagamento recebido','- 100,00')]).length,1);
const fixture=[row('Pagamento recebido','- 344,78'),row('Juros por fatura atrasada','12,98'),row('Multa por fatura atrasada','6,92'),row('IOF por fatura atrasada','1,51'),pending,purchase,row('Zara Brasil - Parcela 4/5','103,66'),row('Shopee - Parcela 4/9','63,48')];
